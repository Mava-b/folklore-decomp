#!/bin/bash
# Lift Folklore's nine SPURS job binaries a second time, at the local-store
# address Sony's real job manager (libsre jm2) loads them to, into
# src/spu_gen_lle/. Those lifts are what runs when firmware_lle/ is present
# (real libsre); src/spu_gen/ (lifted at LS 0) stays for the HLE cellSpurs path.
#
#   PS3RECOMP=../ps3recomp EBOOT=/g/Games/PS3/games/BCUS98147/PS3_GAME/USRDIR/EBOOT.elf tools/relift_lle_jobs.sh
#
# jm2 keeps a cache of job binaries in local store, so a job is not always at
# the same address. Observed under the lifted jm2 (2026-10-18): every job at
# LS 0x4C00 (fetched with GETF in 16 KB pieces, entered at +0x10, just past its
# 16-byte header). With the sound running (Windows) jm2 caches several jobs at
# once, so some also land at 0x12000, 0x18400, 0x1AC00 and 0x1E400. A lift is only valid at
# the address it was made for, so each job is lifted once per address it has
# been seen at. A placement with no lift is still run, by the SPU interpreter,
# and the runtime logs it:
#   [spu-ovl] code from 0x... placed at LS 0x..., which has no lift
# Add that address to the job's list below and re-run this script.
# tools/relift.sh calls this script at the end.
set -e
PS3RECOMP="${PS3RECOMP:-../ps3recomp}"
EBOOT="${EBOOT:-game/EBOOT.elf}"
PYTHON="${PYTHON:-python}"

# guest vaddr : file offset : size (section headers of the v1.00 EBOOT) :
# the LS addresses jm2 has loaded that job to, comma-separated
JOBS="10079e00:5e9e00:d200:4c00 10087000:5f7000:8e80:4c00,12000,1e400
      1008fe80:5ffe80:4680:4c00 10094500:604500:3680:4c00,1ac00
      10097b80:607b80:6180:4c00,12000 1009dd00:60dd00:4b00:4c00
      100a2800:612800:2500:4c00,18400 100a4d00:614d00:4380:4c00
      100a9080:619080:10100:4c00"

mkdir -p analysis/spu_jobs
rm -rf src/spu_gen_lle && mkdir -p src/spu_gen_lle
OUT=src/spu_gen_lle/spu_jobs_lle.c
{
  echo "/* GENERATED by tools/relift_lle_jobs.sh: Folklore's SPURS jobs lifted at"
  echo " * the LS addresses the real jm2 places them at. Each lift is registered as"
  echo " * a code region keyed on its EBOOT address AND its LS address: when the job"
  echo " * manager DMAs that binary to that address, the lift owns the range until"
  echo " * it is replaced. Image ids 50+ keep clear of the runtime's per-title ids"
  echo " * and of the LS-0 lifts in src/spu_gen. */"
  echo "#include <stdint.h>"
  echo "extern void spu_begin_image(int image_id);"
  echo "extern void spu_overlay_register_region_at(uint32_t content_ea, uint32_t span, uint32_t lsa, int image_id);"
  cat <<'HELPER'
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
/* FOLKLORE_INTERP_JOBS=all, or a comma list of image ids (e.g. 50,57): leave
 * those placements unregistered, so the job code they cover runs in the SPU
 * interpreter (with SPU_INTERP_UNLIFTED=1) instead of the lift. An A/B switch
 * for telling a lifting bug apart from anything else. */
static int folklore_job_interpreted(int imageId)
{
    const char* setting = getenv("FOLKLORE_INTERP_JOBS");
    if (!setting || !setting[0])
    {
        return 0;
    }
    if (strcmp(setting, "all") == 0)
    {
        return 1;
    }
    const char* cursor = setting;
    while (*cursor)
    {
        char* end = NULL;
        const long value = strtol(cursor, &end, 10);
        if (end == cursor)
        {
            cursor++;
            continue;
        }
        if (value == imageId)
        {
            return 1;
        }
        cursor = end;
    }
    return 0;
}
HELPER
} > "$OUT.tmp"
REG=""
IMG=50
for JOB in $JOBS; do
    VA=${JOB%%:*}; REST=${JOB#*:}; OFF=${REST%%:*}; REST=${REST#*:}
    SIZE=${REST%%:*}; BASES=${REST#*:}
    BIN="analysis/spu_jobs/job_$VA.bin"
    if [ ! -f "$BIN" ]; then
        "$PYTHON" -I -c "
import sys
data = open(sys.argv[1], 'rb').read()
open(sys.argv[2], 'wb').write(data[int(sys.argv[3], 16):int(sys.argv[3], 16) + int(sys.argv[4], 16)])
" "$EBOOT" "$BIN" "$OFF" "$SIZE"
    fi
    for BASE in ${BASES//,/ }; do
        PFX="jobl_${VA}_${BASE}_"
        "$PYTHON" "$PS3RECOMP/tools/find_spu_functions.py" "$BIN" --raw --base "0x$BASE" \
            --out "analysis/spu_jobs/jobl_${VA}_${BASE}_funcs.json"
        # Switch-table case labels: position-independent code reaches them only
        # through computed branches, so discovery cannot see them.
        EXTRA=$("$PYTHON" -I tools/spu_jump_tables.py "$BIN" --base "0x$BASE")
        EXTRA_ARGS=()
        if [ -n "$EXTRA" ]; then
            EXTRA_ARGS=(--extra-funcs "$EXTRA")
        fi
        mkdir -p "src/spu_gen_lle/job_${VA}_${BASE}"
        "$PYTHON" "$PS3RECOMP/tools/spu_lifter.py" "$BIN" --base "0x$BASE" \
            --functions "analysis/spu_jobs/jobl_${VA}_${BASE}_funcs.json" --return-entries \
            "${EXTRA_ARGS[@]}" \
            --symbol-prefix "$PFX" -o "src/spu_gen_lle/job_${VA}_${BASE}"
        echo "extern void ${PFX}spu_recomp_register(void);" >> "$OUT.tmp"
        REG="$REG    spu_begin_image($IMG); ${PFX}spu_recomp_register();
    if (!folklore_job_interpreted($IMG))
    {
        spu_overlay_register_region_at(0x${VA}u, 0x${SIZE}u, 0x${BASE}u, $IMG);
    }
"
        IMG=$((IMG + 1))
    done
done
{
  echo "__attribute__((constructor)) static void folklore_spu_jobs_lle_register(void)"
  echo "{"
  printf "%s" "$REG"
  echo "    if (getenv(\"FOLKLORE_INTERP_JOBS\"))"
  echo "    {"
  echo "        fprintf(stderr, \"[spu-jobs] FOLKLORE_INTERP_JOBS=%s: those jobs run interpreted\\n\", getenv(\"FOLKLORE_INTERP_JOBS\"));"
  echo "    }"
  echo "    spu_begin_image(0);"
  echo "}"
} >> "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "LLE job lift done"
