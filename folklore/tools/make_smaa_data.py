#!/usr/bin/env python3
"""Builds ps3recomp's libs/video/rsx_smaa_data.h from a checkout of the
reference SMAA (https://github.com/iryoku/smaa, MIT licence): SMAA.hlsl and
the two lookup textures (Textures/AreaTex.h, Textures/SearchTex.h), each
zlib-compressed into a byte array. The renderer inflates them at startup
with stb_image's inflate (stbi_zlib_decode_buffer).

    python make_smaa_data.py <smaa checkout> <output header>
"""
import re
import sys
import zlib


def tableBytes(headerPath):
    text = open(headerPath, encoding='utf-8').read()
    body = text[text.index('{', text.index('static const unsigned char')):]
    body = body[:body.index('}')]
    return bytes(int(value, 16) for value in re.findall(r'0x([0-9a-fA-F]{2})', body))


def byteArray(name, data):
    packed = zlib.compress(data, 9)
    lines = ['static const unsigned int %s_size = %du;' % (name, len(data)),
             'static const unsigned int %s_packed_size = %du;' % (name, len(packed)),
             'static const unsigned char %s_packed[] = {' % name]
    for start in range(0, len(packed), 24):
        lines.append('    ' + ','.join(str(value) for value in packed[start:start + 24]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1
    checkout = sys.argv[1]
    licence = open(checkout + '/LICENSE.txt', encoding='utf-8').read().strip()
    shader = open(checkout + '/SMAA.hlsl', 'rb').read()
    area = tableBytes(checkout + '/Textures/AreaTex.h')
    search = tableBytes(checkout + '/Textures/SearchTex.h')
    if len(area) != 160 * 560 * 2 or len(search) != 64 * 16:
        print('unexpected table sizes: %d, %d' % (len(area), len(search)))
        return 1
    parts = [
        '/*',
        ' * rsx_smaa_data.h -- SMAA 1x for the present pass (rsx_live_draw.c), from',
        ' * the reference implementation, https://github.com/iryoku/smaa: SMAA.hlsl',
        ' * and its two lookup textures (AreaTex 160x560 R8G8, SearchTex 64x16 R8),',
        ' * each zlib-compressed. Generated by folklore/tools/make_smaa_data.py; do',
        ' * not edit. The reference\'s licence:',
        ' *',
    ]
    parts += [(' * ' + line).rstrip() for line in licence.splitlines()]
    parts += [' */', '#ifndef RSX_SMAA_DATA_H', '#define RSX_SMAA_DATA_H', '',
              byteArray('k_smaa_hlsl', shader), '',
              byteArray('k_smaa_area', area), '',
              byteArray('k_smaa_search', search), '',
              '#endif', '']
    open(sys.argv[2], 'w', newline='\n', encoding='utf-8').write('\n'.join(parts))
    return 0


if __name__ == '__main__':
    sys.exit(main())
