#!/bin/bash
# Lift YOUR OWN decrypted libsre.prx (Sony's SPURS library, from dev_flash)
# into firmware_lle/, so the port runs the real SPURS instead of an HLE
# approximation. Run from the folklore/ folder (Git Bash on Windows works):
#
#   PS3RECOMP=../ps3recomp PRX=/i/Recomp/Folklore/libsre.prx tools/lift_firmware.sh
#
# Everything this writes is derived from firmware: keep it on your machine,
# never commit or share firmware_lle/. Without the folder the port builds with
# HLE cellSpurs as before.
#
# Facts about the firmware build this was made against (cellSre_Library, the
# libsre.sprx in RPCS3's dev_flash, decrypted): text 0x0..0x2E000 + data;
# relocated at 0x30000000 the TOC is 0x30039AB0 and the import stubs end at
# 0x3001DB18. SPU side, as offsets into the relocated image:
#   0x20380  SPURS kernel (SPU ELF, LS 0x100..0x880, entry 0x818)
#   0x21480  system service workload, 0x2200 bytes, runs at LS 0xA00
#   0x26300  job-chain policy module (jm2), 0x3E80 bytes, runs at LS 0xA00
# The script checks each of these and stops if your file differs.
set -e
PS3RECOMP="${PS3RECOMP:-../ps3recomp}"
PRX="${PRX:-libsre.prx}"
PYTHON="${PYTHON:-python}"
BASE=0x30000000
TOC=0x30039AB0
CODE_END=0x3001DB18
WORK=analysis/firmware
OUT=firmware_lle

if [ ! -f "$PRX" ]; then
    echo "libsre.prx not found at $PRX -- set PRX=<path to your decrypted libsre.prx>" >&2
    exit 1
fi
mkdir -p "$WORK"
rm -rf "$OUT" && mkdir -p "$OUT/spu"

# ---- PPU side ----------------------------------------------------------------
"$PYTHON" "$PS3RECOMP/tools/lift_prx.py" "$PRX" --base "$BASE" -o "$WORK"
"$PYTHON" -I - "$WORK" <<'EOF'
import json, sys
work = sys.argv[1]
imports = json.load(open(work + "/libsre_imports.json"))
stubs = [{"library": library, "nid": nid.lower(), "stub": stub}
         for library, table in imports.items() for nid, stub in table.items()]
json.dump(stubs, open(work + "/libsre_hle_stubs.json", "w"), indent=1)
EOF
"$PYTHON" "$PS3RECOMP/tools/ppu_lifter.py" "$WORK/libsre_image.bin" --raw \
    --base "$BASE" --toc "$TOC" --code-end "$CODE_END" \
    --functions "$WORK/libsre_functions.json" --hle-stubs "$WORK/libsre_hle_stubs.json" \
    --symbol-prefix libsre_ --source-name libsre_recomp.cpp --header-name libsre_recomp.h \
    --single-file -o "$OUT"
"$PYTHON" "$PS3RECOMP/tools/prx_exports.py" "$PRX" --symbol libsre --out "$OUT/libsre_exports.c"
cp "$WORK/libsre_image.bin" "$OUT/"

# ---- SPU side ----------------------------------------------------------------
"$PYTHON" -I - "$WORK/libsre_image.bin" "$WORK" <<'EOF'
import struct, sys
image = open(sys.argv[1], "rb").read()
work = sys.argv[2]
kernel = 0x20380
if image[kernel:kernel + 4] != b"\x7fELF":
    sys.exit("no SPU ELF at image+0x20380 -- this libsre differs from the one the port was made for")
shoff, = struct.unpack(">I", image[kernel + 0x20:kernel + 0x24])
shentsize, shnum = struct.unpack(">HH", image[kernel + 0x2E:kernel + 0x32])
phoff, = struct.unpack(">I", image[kernel + 0x1C:kernel + 0x20])
phentsize, phnum = struct.unpack(">HH", image[kernel + 0x2A:kernel + 0x2E])
end = shoff + shentsize * shnum
for index in range(phnum):
    header = kernel + phoff + index * phentsize
    offset, = struct.unpack(">I", image[header + 4:header + 8])
    fileSize, = struct.unpack(">I", image[header + 16:header + 20])
    end = max(end, offset + fileSize)
entry, = struct.unpack(">I", image[kernel + 0x18:kernel + 0x1C])
if entry != 0x818:
    sys.exit("SPURS kernel entry is 0x%X, expected 0x818" % entry)
open(work + "/kernel1.elf", "wb").write(image[kernel:kernel + end])
# Workloads: the kernel DMAs them to LS 0xA00. Both start with code (ila/il).
for name, start, size in (("sysservice", 0x21480, 0x2200), ("jm2_pm", 0x26300, 0x3E80)):
    blob = image[start:start + size]
    if len(blob) != size or not any(blob[:16]):
        sys.exit("%s not found at image+0x%X" % (name, start))
    open("%s/%s.bin" % (work, name), "wb").write(blob)
print("SPU images extracted")
EOF
mkdir -p "$OUT/spu/kernel1" "$OUT/spu/sysservice" "$OUT/spu/jm2_pm"
"$PYTHON" "$PS3RECOMP/tools/spu_lifter.py" --auto-functions "$WORK/kernel1.elf" \
    --return-entries --extra-funcs 0x808 --symbol-prefix sre_kernel1_ -o "$OUT/spu/kernel1"
for NAME in sysservice jm2_pm; do
    "$PYTHON" "$PS3RECOMP/tools/find_spu_functions.py" "$WORK/$NAME.bin" --raw --base 0xA00 \
        --out "$WORK/${NAME}_funcs.json"
    "$PYTHON" "$PS3RECOMP/tools/spu_lifter.py" "$WORK/$NAME.bin" --base 0xA00 \
        --functions "$WORK/${NAME}_funcs.json" --return-entries \
        --symbol-prefix "sre_${NAME}_" -o "$OUT/spu/$NAME"
done

cat > "$OUT/spu/libsre_spu_register.c" <<'EOF'
/* GENERATED by tools/lift_firmware.sh -- SPU side of the user's own libsre.
 *
 * Image ids 40+ are kept clear of the runtime's title-specific ids (1, 2, 3,
 * 22) and of Folklore's job images (2..10, 50+).
 *   40  SPURS kernel          LS 0x100..0x880, entry 0x818 (ELF in libsre)
 *   41  system service        LS 0xA00, streamed from libsre+0x21480
 *   42  job-chain PM (jm2)    LS 0xA00, streamed from libsre+0x26300
 * The kernel DMAs whichever workload it selects to LS 0xA00; the source EA of
 * that GET tells the dispatcher which of the two lifts now owns the range.
 */
#include <stdint.h>

extern void spu_begin_image(int image_id);
extern void spu_overlay_register_source(uint32_t content_ea, int image_id);
extern void sre_kernel1_spu_recomp_register(void);
extern void sre_sysservice_spu_recomp_register(void);
extern void sre_jm2_pm_spu_recomp_register(void);

#define LIBSRE_BASE 0x30000000u

__attribute__((constructor)) static void libsre_spu_register(void)
{
    spu_begin_image(40);
    sre_kernel1_spu_recomp_register();
    spu_begin_image(41);
    sre_sysservice_spu_recomp_register();
    spu_overlay_register_source(LIBSRE_BASE + 0x21480u, 41);
    spu_begin_image(42);
    sre_jm2_pm_spu_recomp_register();
    spu_overlay_register_source(LIBSRE_BASE + 0x26300u, 42);
    spu_begin_image(0);
}
EOF
echo "firmware lift done -> $OUT (keep it private)"
