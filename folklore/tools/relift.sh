#!/bin/bash
# Regenerate everything under src/recomp, src/gen and src/spu_gen from the
# decrypted EBOOT. Run from the folklore/ folder (Git Bash on Windows works):
#
#   PS3RECOMP=../ps3recomp EBOOT=/g/Games/PS3/games/BCUS98147/PS3_GAME/USRDIR/EBOOT.elf tools/relift.sh
#
# Two releases are supported, told apart by the decrypted EBOOT's size
# (folklore/docs/REGIONS.md):
#   US  BCUS98147 v1.00  6,518,936 bytes
#   EU  BCES00050 v1.00  6,518,912 bytes
# EBOOT facts this depends on, per release:
#   .text, then .fini, then the import stubs (.lib.stub: 167 in the US EBOOT
#   at 0x4ED6A4..0x4EEB84, 166 in the EU one at 0x4ED65C..0x4EEB1C).
#   --code-end stops just past the stubs; the rest of the R-X segment is
#   .rodata.
#   Nine SPURS job binaries are raw code+data blobs in their own data sections
#   (RPCS3 reports them as "roaming SPU code"), loaded at LS 0. They are the
#   same bytes at the same addresses in both releases.
set -e
PS3RECOMP="${PS3RECOMP:-../ps3recomp}"
EBOOT="${EBOOT:-game/EBOOT.elf}"
PYTHON="${PYTHON:-python}"

EBOOT_SIZE=$(wc -c < "$EBOOT" | tr -d ' ')
case "$EBOOT_SIZE" in
    6518936)
        REGION=US; TITLE_ID=BCUS98147; TOC_BASE=0x0056EB00
        CODE_END=0x4EEB84
        # 0x34D3C8 dispatches through a table base spilled to the stack.
        JT_HINTS="34D3C8:34D3CC:19"
        ;;
    6518912)
        REGION=EU; TITLE_ID=BCES00050; TOC_BASE=0x0056EAF8
        CODE_END=0x4EEB1C
        JT_HINTS="34D380:34D384:19"
        ;;
    *)
        echo "relift.sh: $EBOOT is $EBOOT_SIZE bytes -- not a decrypted EBOOT of a supported release" >&2
        echo "  (BCUS98147 v1.00: 6518936 bytes, BCES00050 v1.00: 6518912 bytes)" >&2
        exit 1
        ;;
esac
echo "relift.sh: $TITLE_ID ($REGION) EBOOT"

mkdir -p analysis
"$PYTHON" "$PS3RECOMP/tools/ppu_loader.py" "$EBOOT" -o analysis/
"$PYTHON" "$PS3RECOMP/tools/find_functions.py" "$EBOOT" \
    --seed-json analysis/EBOOT.functions.json --output analysis/functions.json

# KEEP_GEN=1 (setup.ps1 on a build kit): keep src/gen as shipped. It is made
# from ps3recomp's own NID tables, not the EBOOT, and must match the runtime
# the kit was tested with.
rm -rf src/recomp && mkdir -p src/recomp
if [ -z "$KEEP_GEN" ]; then
    rm -rf src/gen && mkdir -p src/gen
fi
# PPU_JT_HINTS (patches/0015): switch tables the lifter's scan cannot find.
# One function dispatches through a table base spilled to the stack; without
# the hint its 19 cases are an unresolved indirect call and gameplay freezes.
PPU_JT_HINTS="$JT_HINTS" \
"$PYTHON" "$PS3RECOMP/tools/ppu_lifter.py" "$EBOOT" \
    --functions analysis/functions.json \
    --hle-stubs analysis/EBOOT.imports.json \
    --code-end "$CODE_END" --chunks 48 \
    -o src/recomp
if [ -z "$KEEP_GEN" ]; then
    "$PYTHON" "$PS3RECOMP/tools/gen_hle_nids.py" --all --out src/gen/ppu_hle_nids.cpp
fi
# Folklore-specific fixes to the lifted code (each one explained in the script).
"$PYTHON" -I tools/game_patches.py src/recomp --region "$REGION"
# Which release this is, for the engine code (title and size checks, the
# camera constants the aspect-ratio setting changes).
cat > src/recomp/folklore_region.h <<REGION_HEADER
/* GENERATED by tools/relift.sh: the release src/recomp was lifted from. */
#pragma once
#define FOLKLORE_REGION_$REGION 1
#define FOLKLORE_REGION_NAME "$REGION"
#define FOLKLORE_TITLE_ID "$TITLE_ID"
#define FOLKLORE_EBOOT_SIZE ${EBOOT_SIZE}ull
#define FOLKLORE_TOC_BASE ${TOC_BASE}u
REGION_HEADER
# The frame limiter reads the engine menu's settings (tools/patch_limiter.py).
"$PYTHON" -I tools/patch_limiter.py src/recomp/ppu_recomp_*.cpp > /dev/null

# ---- SPURS jobs --------------------------------------------------------------
# guest vaddr : file offset : size (section headers of the v1.00 EBOOT)
JOBS="10079e00:5e9e00:d200 10087000:5f7000:8e80 1008fe80:5ffe80:4680
      10094500:604500:3680 10097b80:607b80:6180 1009dd00:60dd00:4b00
      100a2800:612800:2500 100a4d00:614d00:4380 100a9080:619080:10100"
mkdir -p analysis/spu_jobs
rm -rf src/spu_gen && mkdir -p src/spu_gen
OUT=src/spu_gen/spu_jobs.c
{
  echo "/* GENERATED by tools/relift.sh: Folklore's lifted SPURS job binaries. */"
  echo "#include \"spu_workload.h\""
  echo "extern void spu_begin_image(int image_id);"
} > "$OUT.tmp"
REG=""
IMG=2
for JOB in $JOBS; do
    VA=${JOB%%:*}; REST=${JOB#*:}; OFF=${REST%%:*}; SIZE=${REST#*:}
    BIN="analysis/spu_jobs/job_$VA.bin"
    "$PYTHON" -I -c "
import sys
data = open(sys.argv[1], 'rb').read()
open(sys.argv[2], 'wb').write(data[int(sys.argv[3], 16):int(sys.argv[3], 16) + int(sys.argv[4], 16)])
" "$EBOOT" "$BIN" "$OFF" "$SIZE"
    # The runtime fingerprints a job as FNV-1a 64 over (header size field << 4)
    # bytes, and that size is not the section size: the section is padded to
    # 128 bytes (job 0x10079E00 is 0xD190 bytes in a 0xD200 section) and the
    # binary may itself end in zeros. Register every 16-byte size from just past
    # the last non-zero byte up to the section end; exactly one will match.
    # (tr: Python on Windows ends its lines with CR LF, and $(...) keeps the CR,
    # which turned 0x...ULL into 0x...<CR>ULL in spu_jobs.c.)
    FPS=$("$PYTHON" -I -c "
import sys
data = open(sys.argv[1], 'rb').read()
last = max(index for index, value in enumerate(data) if value)
size = (last + 16) // 16 * 16
while size <= len(data):
    h = 1469598103934665603
    for b in data[:size]:
        h ^= b
        h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    print('%016X' % h)
    size += 16" "$BIN" | tr -d '\r')
    PFX="job_${VA}_"
    "$PYTHON" "$PS3RECOMP/tools/find_spu_functions.py" "$BIN" --raw --base 0 \
        --out "analysis/spu_jobs/job_${VA}_funcs.json"
    mkdir -p "src/spu_gen/job_$VA"
    "$PYTHON" "$PS3RECOMP/tools/spu_lifter.py" "$BIN" --base 0 \
        --functions "analysis/spu_jobs/job_${VA}_funcs.json" \
        --symbol-prefix "$PFX" -o "src/spu_gen/job_$VA"
    echo "extern void ${PFX}spu_func_00000000(spu_context*); extern void ${PFX}spu_recomp_register(void);" >> "$OUT.tmp"
    REG="$REG    spu_begin_image($IMG); ${PFX}spu_recomp_register();
"
    for FP in $FPS; do
        REG="$REG    spu_workload_register_img(0x${FP}ULL, ${PFX}spu_func_00000000, $IMG, \"job_$VA\");
"
    done
    IMG=$((IMG + 1))
done
{
  echo "__attribute__((constructor)) static void folklore_spu_jobs_register(void)"
  echo "{"
  printf "%s" "$REG"
  echo "    spu_begin_image(0);"
  echo "}"
} >> "$OUT.tmp"
mv "$OUT.tmp" "$OUT"

# The same jobs at the LS addresses the real jm2 uses (firmware_lle builds).
PS3RECOMP="$PS3RECOMP" EBOOT="$EBOOT" PYTHON="$PYTHON" bash tools/relift_lle_jobs.sh
echo "relift done"
